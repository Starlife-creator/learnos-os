def build():
    graph = {"version": 1, "units": []}
    all_names = set()
    for (uname, chapters) in UNITS:
        uobj = {"name": uname, "chapters": []}
        for (cname, concepts) in chapters:
            cobj = {"name": cname, "concepts": []}
            for (n, diff, prereq) in concepts:
                all_names.add(n)
                cobj["concepts"].append({"n": n, "d": diff, "p": list(prereq)})
            uobj["chapters"].append(cobj)
        graph["units"].append(uobj)
    n_concepts = len(all_names)
    expl_out = {n: EXPL[n] for n in all_names if n in EXPL}
    missing = [n for n in all_names if n not in EXPL]
    with open(os.path.join(DATA, f"seed_concepts_{SUBJECT}.json"), "w", encoding="utf-8") as f:
        json.dump(graph, f, ensure_ascii=False, indent=2)
    with open(os.path.join(DATA, f"seed_questions_{SUBJECT}.json"), "w", encoding="utf-8") as f:
        json.dump(QUESTIONS, f, ensure_ascii=False, indent=2)
    with open(os.path.join(DATA, f"seed_explanations_{SUBJECT}.json"), "w", encoding="utf-8") as f:
        json.dump(expl_out, f, ensure_ascii=False, indent=2)
    bad = []
    for u in graph["units"]:
        for c in u["chapters"]:
            for cc in c["concepts"]:
                for p in cc["p"]:
                    if p not in all_names:
                        bad.append((cc["n"], p))
    return n_concepts, len(QUESTIONS), len(expl_out), missing, bad


if __name__ == "__main__":
    n_c, n_q, n_e, missing, bad = build()
