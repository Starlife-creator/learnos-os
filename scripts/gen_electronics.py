def build():
    units_out = []
    all_names = set()
    for u_name, chapters in UNITS:
        ch_out = []
        for c_name, concepts in chapters:
            c_out = []
            for (n, d, pre) in concepts:
                c_out.append({"n": n, "d": d, "p": list(pre)})
                all_names.add(n)
            ch_out.append({"name": c_name, "concepts": c_out})
        units_out.append({"name": u_name, "chapters": ch_out})
    graph = {"version": 1, "subject": SUBJECT, "units": units_out}
    bad = [(cc["n"], p) for u in units_out for c in u["chapters"] for cc in c["concepts"] for p in cc.get("p", []) if p not in all_names]
    if bad:
        print("WARN 悬空先修:", bad)
    expl_out = {n: EXPL[n] for n in all_names if n in EXPL}
    missing = [n for n in all_names if n not in EXPL]
    if missing:
        print("WARN 缺详解:", missing)
    with open(os.path.join(DATA, f"seed_concepts_{SUBJECT}.json"), "w", encoding="utf-8") as f:
        json.dump(graph, f, ensure_ascii=False, indent=2)
    with open(os.path.join(DATA, f"seed_questions_{SUBJECT}.json"), "w", encoding="utf-8") as f:
        json.dump({"version": 1, "subject": SUBJECT, "questions": QUESTIONS}, f, ensure_ascii=False, indent=2)
    with open(os.path.join(DATA, f"seed_explanations_{SUBJECT}.json"), "w", encoding="utf-8") as f:
        json.dump(expl_out, f, ensure_ascii=False, indent=2)
    n_concepts = sum(len(c[1]) for u in UNITS for c in u[1])
    print(f"[{SUBJECT}] 单元={len(UNITS)} 章={sum(len(u[1]) for u in UNITS)} "
          f"概念={n_concepts} 题={len(QUESTIONS)} 详解={len(expl_out)}")


if __name__ == "__main__":
    build()
